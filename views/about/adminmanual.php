    <h2 class="h5 fw-bold mt-4 mb-2">3. หน้าตรวจสอบรายงาน</h2>
    <p>หน้านี้แสดงรายงานทั้งหมดที่รอการตรวจสอบเป็นค่าเริ่มต้น (ไม่จำกัดช่วงวันที่ เพื่อไม่ให้รายงานเก่าที่ยังไม่ได้ตรวจตกหล่น) พร้อมตัวกรอง:</p>
    <ul>
        <li>สถานะการตรวจสอบ — รอตรวจสอบ (ค่าเริ่มต้น) / ตรวจแล้ว / ปฏิเสธ / ทุกสถานะ</li>
        <li>ช่วงวันที่ส่งรายงาน (ไม่บังคับ)</li>
    </ul>
    <p>ตารางแสดงคอลัมน์: เลขที่โครงการ, ชื่อโครงการ, หัวหน้าโครงการ, ส่งเมื่อ, ส่งโดย (อีเมล), สถานะการตรวจสอบ, หมายเหตุ (แสดงเหตุผลที่ปฏิเสธแบบย่อ หรือชื่อ/วันที่ผู้ตรวจสอบเมื่ออนุมัติ/ปฏิเสธแล้ว) และปุ่ม "ดูรายละเอียด" มีปุ่มดาวน์โหลดผลลัพธ์ตามตัวกรองปัจจุบันเป็น PDF หรือ Excel ด้านบนตาราง</p>

    <h3 class="h6 fw-bold mt-3 mb-1">การอนุมัติ / ปฏิเสธรายงาน</h3>
    <div class="alert alert-info">
        การอนุมัติและปฏิเสธไม่ได้ทำในหน้าตารางนี้ — ต้องกดปุ่ม "ดูรายละเอียด" เพื่อเข้าไปที่หน้ารายงานฉบับนั้นก่อน จึงจะเห็นปุ่มดำเนินการ
    </div>
    <ol>
        <li>เปิด "ดูรายละเอียด" ของรายงานที่ต้องการตรวจสอบ อ่านข้อมูลทั้งหมดที่ผู้ใช้กรอกไว้</li>
        <li>หากข้อมูลถูกต้องครบถ้วน กดปุ่ม "อนุมัติ / ตรวจแล้ว" แล้วยืนยันในกล่องข้อความที่ปรากฏขึ้น</li>
        <li>หากข้อมูลไม่ถูกต้องหรือไม่ครบถ้วน กดปุ่ม "ปฏิเสธ" — ระบบจะบังคับให้กรอก "เหตุผลที่ปฏิเสธ" ก่อนเสมอ (ช่องนี้เป็นช่องบังคับ ไม่กรอกจะกดยืนยันไม่ได้)</li>
    </ol>
    <div class="alert alert-danger">
        <strong>สำคัญ:</strong> เมื่อกดปฏิเสธและกรอกเหตุผลสำเร็จ ระบบจะส่งอีเมลแจ้งเหตุผลไปยังผู้ส่งรายงาน (submitted_by_email) โดยอัตโนมัติทันที ไม่ต้องส่งอีเมลแจ้งเองซ้ำอีก — ควรกรอกเหตุผลให้ชัดเจนเนื่องจากผู้ส่งจะเห็นข้อความนี้โดยตรง
    </div>

    <h2 class="h5 fw-bold mt-4 mb-2">4. หน้ารายการโครงการ</h2>
    <p>แสดงภาพรวมโครงการทั้งหมดในระบบแบบหนึ่งแถวต่อหนึ่งโครงการ (ไม่ใช่หนึ่งแถวต่อหนึ่งรายงาน) พร้อมสถานะล่าสุดของแต่ละโครงการ ใช้ค้นหาด้วยชื่อโครงการหรือเลขที่โครงการได้ เหมาะสำหรับดูภาพรวมว่าโครงการใดยังไม่ส่งรายงาน หรือค้างอยู่ในสถานะใด</p>

    <h2 class="h5 fw-bold mt-4 mb-2">5. หน้า Dashboard</h2>
    <p>แสดงสถิติภาพรวมของระบบในช่วงเวลาที่เลือก (ค่าเริ่มต้นคือเดือนปัจจุบัน) ประกอบด้วย:</p>
    <ul>
        <li>การ์ดสรุป: จำนวนโครงการทั้งหมดที่ส่งรายงานในช่วงนี้ และจำนวนรายงานที่ส่งเข้ามาทั้งหมด</li>
        <li>กราฟแท่งแบบแบ่งสัดส่วน 3 กราฟ: สถานะการดำเนินโครงการ (นับตามรายงาน), ผลการตรวจสอบ, และสถานะโครงการ (นับตามโครงการ) — กดที่แท่ง/ป้ายกำกับเพื่อกรองตารางด้านล่างได้ กดซ้ำเพื่อยกเลิกตัวกรอง</li>
        <li>ตารางโครงการล่าสุด และตารางรายงานล่าสุด (แยกกัน คนละหน้า/การเรียงลำดับ)</li>
        <li>ตารางสถิติเพิ่มเติม: สรุปจำนวนการใช้สัตว์ตามหน่วยนับ, จำนวนผลงานตีพิมพ์แยกตามระดับ, และจำนวนการยื่นจดทรัพย์สินทางปัญญา</li>
    </ul>
    <p>มีปุ่ม "ดาวน์โหลด PDF" และ "ดาวน์โหลด Excel" สำหรับส่งออกข้อมูลทั้งหมดตามช่วงวันที่ที่กรองไว้ (ไม่จำกัดแค่ที่แสดงบนหน้าจอ) — ไฟล์ Excel มี 3 แผ่นงาน: สรุปภาพรวม, รายการโครงการ, และรายงาน</p>

    <h2 class="h5 fw-bold mt-4 mb-2">6. หน้าจัดการอีเมล (Email)</h2>
    <h3 class="h6 fw-bold mt-3 mb-1">6.1 ค้นหาโครงการ</h3>
    <p>ใช้ตัวกรองด้านบนเพื่อเลือกกลุ่มโครงการที่จะส่งอีเมลถึง:</p>
    <div class="table-responsive mb-3">
        <table class="table table-sm table-bordered">
            <thead class="table-light"><tr><th>ตัวกรอง</th><th>ความหมาย</th></tr></thead>
            <tbody>
            <tr><td>สถานะการดำเนินโครงการ</td><td>ยังไม่เสร็จ (ค่าเริ่มต้น — ยังไม่เริ่ม/อยู่ระหว่างดำเนินการ) หรือ ทุกสถานะ</td></tr>
            <tr><td>ส่งรายงานล่าสุดตั้งแต่ / ถึงวันที่</td><td>กรองจากวันที่ส่งรายงานฉบับล่าสุดของแต่ละโครงการ — โครงการที่ยังไม่เคยส่งรายงานเลยจะไม่ปรากฏถ้าเลือกช่วงนี้</td></tr>
            <tr><td>วันที่ประชุมตั้งแต่ / ถึงวันที่</td><td>กรองจากวันที่ประชุมพิจารณาโครงการ — ใช้ได้กับโครงการทุกสถานะ ไม่ว่าจะเคยส่งรายงานหรือไม่</td></tr>
            </tbody>
        </table>
    </div>
    <div class="alert alert-info">ตัวกรองทั้งสองชุด (วันที่ส่งรายงาน และวันที่ประชุม) ใช้ร่วมกันได้พร้อมกัน ระบบจะกรองแบบ "และ" (ต้องตรงเงื่อนไขทุกตัวที่ระบุ)</div>

    <h3 class="h6 fw-bold mt-3 mb-1">6.2 การเขียนและส่งอีเมล</h3>
    <ol>
        <li>ติ๊กเลือกโครงการที่ต้องการส่งจากตารางผลลัพธ์ (หรือติ๊ก checkbox บนหัวตารางเพื่อเลือกทั้งหมด)</li>
        <li>เลือกเทมเพลตอีเมล: "ข่าวสารทั่วไป" (เริ่มจากว่าง กรอกหัวข้อ/เนื้อหาเอง) หรือ "แจ้งเตือนส่งรายงาน" (ระบบสร้างเนื้อหาหลักอัตโนมัติแยกตามแต่ละโครงการ พร้อมช่องกำหนดวันครบกำหนดส่งรายงาน)</li>
        <li>กรอกหัวข้ออีเมล และเนื้อหา (กรณีเทมเพลตแจ้งเตือน เนื้อหาที่กรอกจะถูกแนบเพิ่มท้ายอีเมลเท่านั้น ไม่ใช่เนื้อหาหลัก)</li>
        <li>กดปุ่ม "ส่งอีเมล" แล้วยืนยันในกล่องข้อความที่ปรากฏขึ้น</li>
    </ol>
    <div class="alert alert-danger">
        <strong>สำคัญ:</strong> หากตัวแปรสภาพแวดล้อม MAILER_TEST_OVERRIDE_TO ยังเปิดใช้งานอยู่บนเซิร์ฟเวอร์ อีเมลทุกฉบับที่ส่ง "ถึงโครงการ" จะถูกส่งไปที่อีเมลทดสอบแทนอีเมลจริงของโครงการทั้งหมด (แต่ระบบยังคงบันทึกอีเมลผู้รับจริงไว้ในประวัติเพื่อการตรวจสอบ) ต้องปิดค่านี้ก่อนใช้งานจริงกับผู้ใช้จริง — ดูรายละเอียดกับผู้ดูแลระบบด้านเทคนิค
    </div>

    <h3 class="h6 fw-bold mt-3 mb-1">6.3 ประวัติการแจ้งเตือน / ข่าวสาร</h3>
    <p>ตารางด้านล่างของหน้าเดียวกัน แสดงประวัติการส่งอีเมลทั้งหมด (ทั้งจากหน้านี้และจากระบบแจ้งเตือนอัตโนมัติ) มีตัวกรองแยกต่างหาก: ช่วงวันที่ส่ง และค้นหาจากชื่อโครงการ/อีเมลผู้รับ แต่ละแถวแสดงสถานะการส่ง (สำเร็จ/ล้มเหลว) หากล้มเหลวสามารถชี้เมาส์ที่ป้ายสถานะเพื่อดูสาเหตุได้</p>

    <h2 class="h5 fw-bold mt-4 mb-2">7. หน้าตั้งค่าแจ้งเตือน (รอบการแจ้งเตือนอัตโนมัติ)</h2>
    <p>หน้านี้จัดการ "รอบการแจ้งเตือน" (reminder cycle) ซึ่งเป็นกลไกแจ้งเตือนอัตโนมัติ แยกจากการส่งอีเมลแบบครั้งเดียวในเมนู Email</p>

    <h3 class="h6 fw-bold mt-3 mb-1">7.1 การสร้างรอบใหม่</h3>
    <p>กรอกข้อมูล 3 ช่อง:</p>
    <ul>
        <li>ชื่อรอบ — ข้อความอิสระเพื่อใช้อ้างอิง เช่น "รอบที่ 1/2569"</li>
        <li>กำหนดการส่งรายงาน — วันครบกำหนดที่จะปรากฏในเนื้อหาอีเมลแจ้งเตือน</li>
        <li>วันที่ส่งอีเมลแจ้งเตือน — วันที่ต้องการให้ระบบส่งอีเมลจริง</li>
    </ul>

    <h3 class="h6 fw-bold mt-3 mb-1">7.2 การทำงานอัตโนมัติ</h3>
    <p>ระบบมีตัวจับเวลาอัตโนมัติ (cron) ทำงานทุกวันเวลา 09:00 น. ตรวจสอบว่ามีรอบใดถึง "วันที่ส่งอีเมลแจ้งเตือน" แล้วหรือยัง หากถึงกำหนด (รวมถึงกรณีเลยกำหนดมาแล้วแต่ยังไม่เคยส่ง) ระบบจะส่งอีเมลแจ้งเตือนไปยัง "โครงการที่ยังค้างอยู่ทั้งหมด" ณ ขณะนั้นโดยอัตโนมัติทันที (ยังไม่เริ่มดำเนินการ/อยู่ระหว่างดำเนินการ หรือยังไม่เคยส่งรายงานเลย)</p>

    <h3 class="h6 fw-bold mt-3 mb-1">7.3 การส่งด้วยตนเองก่อนถึงกำหนด</h3>
    <div class="alert alert-info">
        รอบที่ยังไม่ถูกส่ง สามารถกดปุ่ม "ส่งตอนนี้เลย" เพื่อบังคับให้ระบบส่งทันทีโดยไม่ต้องรอถึงวันที่กำหนดไว้ — มีกล่องยืนยันก่อนดำเนินการ มีประโยชน์เมื่อต้องการทดสอบ หรือมีความจำเป็นต้องแจ้งเตือนเร่งด่วนก่อนกำหนด
    </div>

